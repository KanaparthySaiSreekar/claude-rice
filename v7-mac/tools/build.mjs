// build.mjs: the macOS half of the v2 rice. Pure functions from one palette (v2-win/palette/palettes.json) to the files
// that replace Windows Terminal, PowerShell and the .cmd status-line shim on a Mac: Ghostty, fish (with eza for ls) and a
// plain command line for the status line. The Claude Code theme, the status line palette and the Bridge palette come from
// v2's own builders unchanged.
import { parseHex } from "../../v2-win/tools/lib/color.mjs"

const rgb = (hex) => parseHex(hex).join(";")
const bare = (hex) => hex.replace(/^#/, "")
const sq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`

// ---------------------------------------------------------------------------------------------
// Ghostty (replaces Windows Terminal). Lean on purpose: no transparency, blur, background picture or shader, each of
// which costs GPU work on every frame; v2's glow shader is off for ember anyway (it softened the text).
// ---------------------------------------------------------------------------------------------
export function ghosttyConfig(p, { shell, fontSize = 13 } = {}) {
  const a = p.ansi
  const order = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white",
    "brightBlack", "brightRed", "brightGreen", "brightYellow", "brightBlue", "brightPurple", "brightCyan", "brightWhite"]
  return `# Ghostty, generated by the rice (palette: ${p.label}). Regenerate with:  node v7-mac/tools/mac.mjs apply ${p.key}
# Edits here are overwritten by the next apply; change v2-win/palette/palettes.json or v7-mac/tools/build.mjs instead.

# --- shell: fish for interactive use; the login shell stays zsh, so Claude Code's Bash tool keeps a POSIX shell ---
${shell ? `command = ${shell}\n` : ""}
# --- font: the face the status line's glyph list was checked against (JetBrainsMono NFM) ---
font-family = "JetBrainsMono Nerd Font Mono"
font-size = ${fontSize}

# --- colours (${p.label}) ---
background = ${p.base.bg}
foreground = ${p.base.fg}
cursor-color = ${p.accent.coral}
cursor-text = ${p.base.bg}
selection-background = ${p.base.selection}
selection-foreground = ${p.base.fg}
${order.map((k, i) => `palette = ${i}=${a[k]}`).join("\n")}

# --- window: flat colour, the title bar and tabs drawn in the terminal's own colours ---
window-theme = ghostty
macos-titlebar-style = tabs
background-opacity = 1
window-padding-x = 18
window-padding-y = 12
window-padding-balance = true
cursor-style = bar
mouse-hide-while-typing = true

# --- keys: left Option is Alt (Claude Code's Option shortcuts); right Option still types special characters ---
macos-option-as-alt = left

# --- the dock icon in the palette ---
macos-icon = custom-style
macos-icon-ghost-color = ${p.accent.coral}
macos-icon-screen-color = ${p.base.bg}
`
}

// ---------------------------------------------------------------------------------------------
// eza colours for ls (replaces the PowerShell profile's icon ls): the same groups and palette slots
// ---------------------------------------------------------------------------------------------
export const LS_GROUPS = [
  ["script", ["ps1", "psm1", "psd1", "sh", "bash", "zsh", "fish", "bat", "cmd"], (p) => p.accent.amber],
  ["code", ["py", "js", "mjs", "cjs", "ts", "mts", "jsx", "tsx", "c", "cpp", "h", "hpp", "cs", "go", "rs", "java", "kt", "swift", "rb", "php", "lua", "html", "css", "zig"], (p) => p.accent.coralLight],
  ["config", ["json", "jsonc", "yaml", "yml", "toml", "xml", "ini", "cfg", "conf", "env", "plist", "ghostty"], (p) => p.accent.cyan],
  ["text", ["md", "markdown", "rst", "txt", "log", "nfo"], (p) => p.base.muted],
  ["docs", ["pdf", "doc", "docx", "odt", "rtf", "pages"], (p) => p.accent.red],
  ["sheets", ["xls", "xlsx", "csv", "ods", "numbers"], (p) => p.accent.mint],
  ["slides", ["ppt", "pptx", "odp", "key"], (p) => p.accent.coral],
  ["images", ["png", "jpg", "jpeg", "gif", "bmp", "webp", "svg", "ico", "tif", "tiff", "heic"], (p) => p.accent.violet],
  ["video", ["mp4", "mkv", "avi", "mov", "webm", "flv", "wmv"], (p) => p.accent.pink],
  ["audio", ["mp3", "wav", "flac", "ogg", "m4a", "aac", "aiff"], (p) => p.accent.blue],
  ["archives", ["zip", "rar", "7z", "tar", "gz", "xz", "bz2", "zst", "tgz"], (p) => p.darker(p.accent.amber, 0.2)],
  ["executables", ["exe", "msi", "com", "appx", "app", "dmg", "pkg"], (p) => p.accent.red],
]

export function ezaColors(p) {
  const parts = [`di=38;2;${rgb(p.accent.coral)}`, `fi=38;2;${rgb(p.base.muted)}`, `ex=38;2;${rgb(p.accent.amber)}`, `ln=38;2;${rgb(p.accent.cyan)}`]
  for (const [, exts, colour] of LS_GROUPS) for (const e of exts) parts.push(`*.${e}=38;2;${rgb(colour(p))}`)
  return parts.join(":")
}

// ---------------------------------------------------------------------------------------------
// fish (replaces the PowerShell profile). Native fish only: its own highlighting, history suggestions and completion
// pager stand in for PSReadLine; no plugins and no prompt framework. The prompt reads .git/HEAD with builtins, so it
// never starts git (nothing inside the repository you are in can run) and never forks at all.
// ---------------------------------------------------------------------------------------------
export function fishRice(p) {
  const a = p.accent, b = p.base
  return `# fish, generated by the rice (palette: ${p.label}). Regenerate with:  node v7-mac/tools/mac.mjs apply ${p.key}
# Edits here are overwritten by the next apply. Your own settings belong in ~/.config/fish/config.fish.
status is-interactive; or return

set -g fish_greeting

# --- syntax highlight colours (${p.label}), as the PowerShell profile had them ---
set -g fish_color_normal ${bare(b.fg)}
set -g fish_color_command ${bare(a.coral)}
set -g fish_color_keyword ${bare(a.coral)}
set -g fish_color_param ${bare(a.coralLight)}
set -g fish_color_option ${bare(a.coralLight)}
set -g fish_color_quote ${bare(a.mint)}
set -g fish_color_escape ${bare(a.amber)}
set -g fish_color_operator ${bare(a.pink)}
set -g fish_color_redirection ${bare(a.pink)}
set -g fish_color_end ${bare(a.pink)}
set -g fish_color_comment ${bare(b.faint)}
set -g fish_color_error ${bare(a.red)}
set -g fish_color_valid_path --underline
set -g fish_color_autosuggestion ${bare(b.dim)}
set -g fish_color_selection --background=${bare(b.selection)}
set -g fish_color_search_match --background=${bare(b.selection)}
set -g fish_color_cancel ${bare(a.red)}
set -g fish_pager_color_prefix ${bare(a.coral)} --bold
set -g fish_pager_color_completion ${bare(b.fg)}
set -g fish_pager_color_description ${bare(b.faint)}
set -g fish_pager_color_progress ${bare(b.bg)} --background=${bare(a.coral)}
set -g fish_pager_color_selected_background --background=${bare(b.hover)}

# --- ls: Nerd Font icons, colour by type, folders first (eza, coloured from the palette) ---
set -gx EZA_COLORS '${ezaColors(p)}'
function ls --wraps eza --description 'eza: icons, colour by type, folders first'
    eza -a --icons=auto --group-directories-first $argv
end

# --- prompt: folder, git branch (read from .git/HEAD, no git process), an arrow that shows the last result ---
function __rice_branch --description 'the checked-out branch, read from .git/HEAD'
    set -l dir $PWD
    while true
        if test -d $dir/.git
            read -l head < $dir/.git/HEAD 2>/dev/null; or return
            string replace -rf '^ref:\\s*refs/heads/' '' -- $head
            return
        else if test -f $dir/.git
            read -l pointer < $dir/.git 2>/dev/null; or return
            set -l gitdir (string replace -rf '^gitdir:\\s*' '' -- $pointer); or return
            string match -q '/*' -- $gitdir; or set gitdir $dir/$gitdir
            read -l head < $gitdir/HEAD 2>/dev/null; or return
            string replace -rf '^ref:\\s*refs/heads/' '' -- $head
            return
        end
        test "$dir" = /; and return
        set dir (path dirname -- $dir)
    end
end

function fish_prompt
    set -l ok $status
    set -l where $PWD
    if string match -q -- "$HOME" $PWD; or string match -q -- "$HOME/*" $PWD
        set where "~"(string sub -s (math (string length -- $HOME) + 1) -- $PWD)
    end
    set -l branch (__rice_branch)
    echo
    set_color ${bare(a.violet)}; printf ' %s' $where
    if test -n "$branch"
        set_color ${bare(b.faint)}; printf ' \\u2325 '
        set_color ${bare(a.pink)}; printf '%s' (string replace -ra '[\\x00-\\x1f\\x7f]' '' -- $branch)
    end
    if test $ok -eq 0; set_color ${bare(a.coral)}; else; set_color ${bare(a.red)}; end
    printf ' \\u276F'
    set_color normal
    printf ' '
end
`
}

/** The user's own fish config, made once from what ~/.zshrc and ~/.zprofile set (PATH and aliases); apply never overwrites it. */
export function fishConfig({ paths = [], aliases = {}, env = {} } = {}) {
  return `# Your fish config. Made once by v7-mac/tools/mac.mjs from ~/.zshrc and ~/.zprofile; the rice never overwrites it
# (its colours and prompt are in conf.d/rice.fish).

# Homebrew, set directly instead of \`brew shellenv\` so a new shell starts no process
${Object.entries(env).map(([k, v]) => `set -gx ${k} ${sq(v)}`).join("\n")}
fish_add_path --path --move ${paths.map(sq).join(" ")}

${Object.entries(aliases).map(([k, v]) => `alias ${k} ${sq(v)}`).join("\n")}
`
}

/** The status line command: node by absolute path straight to the deck, no shim and no PATH lookup. v2's blank spacer row was
 *  too much gap and none was too little (2026-10-20): AURORA_DECK_GAP=0 drops the row and AURORA_DECK_BARS=half draws the
 *  gauges in the lower half of theirs, which leaves half a row between the pills and the bars. */
export const deckCommand = (node, deck) => `AURORA_DECK_GAP=0 AURORA_DECK_BARS=half exec ${sq(node)} ${sq(deck)}`
